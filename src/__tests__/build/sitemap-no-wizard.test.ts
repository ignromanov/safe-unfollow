import { existsSync, readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

import { describe, it, expect } from 'vitest';

import { SUPPORTED_LANGUAGES } from '@/config/languages';

/**
 * The one SEO invariant of the route removal (GH#102, PR 3) a unit test can prove.
 *
 * The eight `/wizard` addresses were 90 of the sitemap's 163 `<loc>` entries — 55.2% of
 * everything we asked Google to crawl, and 80 of those 90 were already canonicalized
 * away to `/wizard`, so the crawl budget was being spent on pages that pointed at each
 * other. `vercel.json` now 301s every one of them to `/upload`; a sitemap that keeps
 * listing them advertises a redirect chain as a destination.
 *
 * This asserts on `dist/sitemap.xml` rather than on `ROUTE_CONFIG`, because the sitemap
 * is generated by scanning the built HTML: a route can vanish from the config and still
 * be emitted if `includedRoutes` still prerenders a page for it. Only the artefact
 * proves both halves are gone.
 *
 * `describe.runIf(built)` like the other prerender suites: this only runs against
 * `dist/`, which only `ci.yml` produces before the tests. A dist-less local run skips it
 * rather than failing, and that skip is not a pass.
 */
const dist = resolve(__dirname, '../../../dist');
const sitemapPath = join(dist, 'sitemap.xml');
const built = existsSync(dist) && existsSync(sitemapPath);

describe.runIf(built)('sitemap after the wizard routes were removed', () => {
  const xml = built ? readFileSync(sitemapPath, 'utf-8') : '';
  const locations = [...xml.matchAll(/<loc>([^<]*)<\/loc>/g)].map(match => match[1]);

  it('reads a sitemap with entries in it', () => {
    // Guards the guard: an empty sitemap would satisfy every assertion below for the
    // wrong reason.
    expect(locations.length).toBeGreaterThan(50);
  });

  it('emits no sitemap entry containing "wizard"', () => {
    expect(locations.filter(loc => loc.includes('wizard'))).toEqual([]);
  });

  // Derived from SUPPORTED_LANGUAGES rather than hand-listed: the ten redirect
  // destinations are one per locale, and pinning only the English one let a regression
  // that dropped the nine localized `/upload` pages from the sitemap pass green — while
  // nine of the ten sets of 301s pointed at pages Google had never been asked to crawl.
  const uploadUrl = (lang: string) =>
    lang === 'en' ? 'https://safeunfollow.app/upload' : `https://safeunfollow.app/${lang}/upload`;

  it.each(SUPPORTED_LANGUAGES)(
    "still lists the %s /upload, which is where that locale's 301s land",
    lang => {
      // The removal must shrink the sitemap, not empty it: the destination of every
      // redirect rule has to stay crawlable.
      expect(locations).toContain(uploadUrl(lang));
    }
  );
});
